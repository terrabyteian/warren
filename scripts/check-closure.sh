#!/usr/bin/env bash
# Per-binary transitive closure report and growth gate.
#
# For each shipped binary, and the client core the native shells link, lists
# every third-party crate compiled into it (normal and build dependencies,
# proc macros included) across the release targets, then compares that list
# with the committed baseline in deps/closure/. Any difference fails: a new
# crate or version is growth that needs review, and a stale baseline must be
# refreshed. Data-path builds also fail if they reach any crate named in
# deps/data-path-forbidden.txt.
#
# Usage: scripts/check-closure.sh [--update]
set -euo pipefail

cd "$(dirname "$0")/.."

# Release targets; keep in sync with [graph] targets in deny.toml.
targets="x86_64-unknown-linux-gnu aarch64-unknown-linux-gnu x86_64-unknown-linux-musl
aarch64-unknown-linux-musl aarch64-apple-darwin x86_64-apple-darwin"

# name|data path?|cargo tree package and feature selection
binaries="warren|no|-p warren
warren-datapath|yes|-p warren --no-default-features --features relay,connector
warren-client|yes|-p warren-client"

update=0
case "${1:-}" in
  --update) update=1 ;;
  "") ;;
  *)
    echo "usage: $0 [--update]" >&2
    exit 2
    ;;
esac

target_args=""
for t in $targets; do
  target_args="$target_args --target $t"
done

forbidden=$(grep -v '^[[:space:]]*#' deps/data-path-forbidden.txt | awk 'NF { print $1 }')

# Every crate in the closure, one "name version" or "name version (path)" per line.
closure() {
  # shellcheck disable=SC2086 # word splitting is intended for both argument lists
  cargo tree --color never --locked --offline -e normal,build --prefix none -f '{p}' $1 $target_args |
    sed -e 's/ (\*)$//' -e 's/ (proc-macro)$//' | LC_ALL=C sort -u
}

drift=0
forbidden_hit=0
summary=""
while IFS='|' read -r name datapath selection; do
  all=$(closure "$selection")
  # Workspace crates carry their path in parentheses; the rest are third party.
  third=$(printf '%s\n' "$all" | grep -v ' (' || true)
  count=$(printf '%s\n' "$third" | awk 'NF' | wc -l | tr -d ' ')
  baseline="deps/closure/$name.txt"
  status=ok

  if [ "$datapath" = yes ]; then
    for crate in $(printf '%s\n' "$all" | awk '{ print $1 }'); do
      if printf '%s\n' "$forbidden" | grep -qxF "$crate"; then
        echo "error: data-path build $name reaches forbidden crate $crate" >&2
        status=FORBIDDEN
        forbidden_hit=1
      fi
    done
  fi

  if [ "$status" = FORBIDDEN ]; then
    : # never record a baseline that includes a forbidden crate
  elif [ "$update" -eq 1 ]; then
    mkdir -p deps/closure
    {
      echo "# Third-party crates compiled into $name ($selection),"
      echo "# across the release targets. Generated by scripts/check-closure.sh --update."
      printf '%s\n' "$third" | awk 'NF'
    } >"$baseline"
    status=updated
  elif [ ! -f "$baseline" ]; then
    echo "error: no baseline $baseline; run scripts/check-closure.sh --update" >&2
    status=MISSING
    drift=1
  else
    expected=$(awk '!/^#/ && NF' "$baseline" | LC_ALL=C sort -u)
    added=$(LC_ALL=C comm -13 <(printf '%s\n' "$expected" | awk 'NF') <(printf '%s\n' "$third" | awk 'NF'))
    removed=$(LC_ALL=C comm -23 <(printf '%s\n' "$expected" | awk 'NF') <(printf '%s\n' "$third" | awk 'NF'))
    if [ -n "$added" ]; then
      echo "error: closure of $name grew beyond $baseline:" >&2
      printf '%s\n' "$added" | sed 's/^/  + /' >&2
      status=GREW
      drift=1
    fi
    if [ -n "$removed" ]; then
      echo "error: $baseline lists crates no longer in the closure of $name:" >&2
      printf '%s\n' "$removed" | sed 's/^/  - /' >&2
      [ "$status" = ok ] && status=STALE
      drift=1
    fi
  fi

  printf '%-16s data-path=%-3s third-party crates=%-4s %s\n' "$name" "$datapath" "$count" "$status"
  summary="$summary| $name | $datapath | $count | $status |
"
done <<<"$binaries"

if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
  {
    echo "### Dependency closure per binary"
    echo
    echo "| binary | data path | third-party crates | status |"
    echo "| --- | --- | --- | --- |"
    printf '%s' "$summary"
  } >>"$GITHUB_STEP_SUMMARY"
fi

if [ "$forbidden_hit" -ne 0 ]; then
  echo "closure check: FAILED. Data-path builds must not link the crates in" >&2
  echo "deps/data-path-forbidden.txt; move the dependency out of the data path." >&2
fi
if [ "$drift" -ne 0 ]; then
  echo "closure check: FAILED. If the change is intended, run scripts/check-closure.sh --update," >&2
  echo "commit the baseline, and justify the growth in the pull request (docs/dependencies.md)." >&2
fi
if [ "$forbidden_hit" -ne 0 ] || [ "$drift" -ne 0 ]; then
  exit 1
fi
